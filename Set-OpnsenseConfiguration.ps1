# Set environment variable secrets for this session
$env:FW_HOST = "<YOUR_HOST>"
$env:FW_USER = "<API_KEY>"
$env:FW_PASS = "<API_SECRET>"
$env:FW_PSK = "<IPSEC_PSK>" # assumes firewalls are deployed in two regions with IPsec peering between them

# Define other variables
